function fromTag(tag: string): Lang {
  return tag.trim().toLowerCase().startsWith("es") ? "es" : "en";
}

/** Fallback for the platforms Rust answers nothing for. */
let lang: Lang = fromTag(
  (() => {
    try {
      return navigator.language ?? "";
    } catch {
      return "";
    }
  })(),
);

export function setLocale(tag: string) {
  if (tag.trim()) lang = fromTag(tag);
}

export function getLocale(): Lang {
  return lang;
}

/**
 * Status lines come from Rust already interpolated, so an exact-key lookup cannot
 * match them. One pattern per shape; anything unmatched stays as it came.
 */
const SEGMENTS: [RegExp, string][] = [
  [/^(\d+) of (\d+) running$/, "$1 de $2 corriendo"],
  [/^(\d+) stopped$/, "$1 detenidos"],
  [/^(\d+) running$/, "$1 corriendo"],
  [/^tunnel (.+) up$/, "túnel $1 arriba"],
  [/^Sealed \((.+)\)$/, "Sellado ($1)"],
  [/^exited \(code (\d+)\)$/, "terminó (código $1)"],
  [/^started \(pid (\d+)\)$/, "arrancado (pid $1)"],
  [/^stopped \(pid (\d+)\)$/, "detenido (pid $1)"],
  [/^binary missing: (.+)$/, "falta el binario: $1"],
  [/^cloudflared missing$/, "falta cloudflared"],
];

function segment(text: string): string {
  const exact = ES[text];
  if (exact) return exact;
  for (const [re, replacement] of SEGMENTS) {
    if (re.test(text)) return text.replace(re, replacement);
  }
  return text;
}

/** Translate an English source string. Unknown keys pass through unchanged. */
export function t(en: string): string {
  if (lang === "en") return en;
  const hit = ES[en];
  if (hit) return hit;
  // A status line is segments joined by " · ": translate each one on its own.
  if (en.includes(" · ")) return en.split(" · ").map(segment).join(" · ");
  return segment(en);
}

